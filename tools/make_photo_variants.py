#!/usr/bin/env python3
"""Make every photo the website shows from the originals in photos/.

The originals in photos/ are never published (tools/build-site.sh leaves the
folder out). For each photo a page uses, this script writes into img/:

  - the web copy the page shows: at most 1200 pixels wide, compressed, with a
    visible Horizon Media watermark;
  - the smaller busy-mode copies in img/lite/ and img/saver/, watermarked too;
  - the list busy mode reads (netlify/guard/photo-variants.js).

Run it from anywhere after adding or replacing a photo:

    python3 tools/make_photo_variants.py           # make what is missing or out of date
    python3 tools/make_photo_variants.py --force   # remake everything (after changing a setting)
    python3 tools/make_photo_variants.py --check   # change nothing; exit 1 if out of date

Adding a photo: put the original in photos/ at the same path the page will use
under img/ (photos/game-day.jpg is shown as img/game-day.jpg), add it to the
page, and run the script. Needs Pillow (pip install pillow).
"""

import argparse
import hashlib
import io
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "photos"
PAGES = [ROOT / "index.html", ROOT / "portfolio.html"]
MANIFEST = ROOT / "netlify" / "guard" / "photo-variants.js"
FONT = ROOT / "fonts" / "big-shoulders-display-latin.woff2"

# Widest each copy may be, in pixels, by how the page uses the photo, and its JPEG quality.
SIZES = {
    "web": {"img": 1200, "background": 1200, "thumb": 480, "quality": 80},
    "lite": {"img": 480, "background": 640, "quality": 58},
    "saver": {"img": 320, "background": 480, "quality": 40},
}
# A busy-mode copy is only kept if it is at most this fraction of the web copy's size.
WORTHWHILE = 0.9
# Originals narrower than this (the team's round profile pictures) get no
# watermark on any copy: it would be unreadable at that size.
WATERMARK_MIN_WIDTH = 400
# Where the watermark sits: right-aligned, with its bottom edge this far down the
# photo. Pages crop photos to fit their frames (phones crop the homepage tiles to
# the middle of the photo), and this keeps the mark inside every crop.
WATERMARK_BOTTOM = 0.76
WATERMARK_WIDTH = 0.30  # of the photo's width

MANIFEST_HEADER = """\
// Generated by tools/make_photo_variants.py. Do not edit by hand.
// Every photo the pages show, the original (in photos/) it was made from, and,
// for busy mode, where its smaller copies are.
export default """

IMG_TAG = re.compile(r"""\s(?:src|data-full)=["'](img/[^"'?#]+)["']""")
CSS_URL = re.compile(r"""url\(\s*["']?(img/[^"')?#]+)["']?\s*\)""")


def page_photos():
    """Photos the pages show, mapped to how each is used: "img", "background" or "thumb"."""
    html = "\n".join(page.read_text(encoding="utf-8") for page in PAGES if page.is_file())
    found = {}
    for kind, pattern in (("img", IMG_TAG), ("background", CSS_URL)):
        for path in pattern.findall(html):
            if not path.lower().endswith((".jpg", ".jpeg")) or ".." in path.split("/"):
                continue
            if any(path.startswith(f"img/{level}/") for level in ("lite", "saver")):
                continue  # already a busy-mode copy
            use = "thumb" if "/thumb/" in path else kind
            # A photo used both ways keeps the larger (background) size.
            if found.get(path) != "background":
                found[path] = use
    return dict(sorted(found.items()))


def source_of(photo):
    """photos/<path> for img/<path>; a grid thumbnail is made from its full-size original."""
    return SOURCES / photo[len("img/"):].replace("/thumb/", "/")


def fingerprint(file):
    return hashlib.sha256(file.read_bytes()).hexdigest()[:16]


def variant_path(photo, level):
    return f"img/{level}/{photo[len('img/'):]}"


def read_manifest():
    if not MANIFEST.is_file():
        return {}
    text = MANIFEST.read_text(encoding="utf-8")
    try:
        return json.loads(text[text.index("export default") + len("export default"):].rstrip().rstrip(";"))
    except ValueError:
        return {}


def write_manifest(manifest):
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(MANIFEST_HEADER + json.dumps(manifest, indent=2) + ";\n", encoding="utf-8")


# ---- Making the copies -------------------------------------------------------

def open_source(file):
    """The original, upright and in sRGB colours."""
    from PIL import Image, ImageCms, ImageOps

    with Image.open(file) as opened:
        image = ImageOps.exif_transpose(opened)
        profile = image.info.get("icc_profile")
        if profile:
            try:
                image = ImageCms.profileToProfile(
                    image.convert("RGB"),
                    ImageCms.ImageCmsProfile(io.BytesIO(profile)),
                    ImageCms.createProfile("sRGB"),
                    outputMode="RGB",
                )
            except Exception:
                pass
        return image.convert("RGB")


def watermark(image):
    """Draws the Horizon Media mark (the logo's three slashes and the name) onto the photo."""
    from PIL import Image, ImageDraw, ImageFilter, ImageFont

    size = max(8, round(image.width * WATERMARK_WIDTH / 5.2))
    font = ImageFont.truetype(str(FONT), size)
    try:
        font.set_variation_by_axes([800])  # the heavy weight the site's headings use
    except Exception:
        pass
    text = "HORIZON MEDIA"
    left, top, right, bottom = font.getbbox(text)
    cap = bottom - top
    slash_w, gap = cap * 0.62, cap * 0.18
    mark_w = 3 * slash_w + 2 * gap + cap * 0.35 + (right - left)
    x0 = image.width * 0.95 - mark_w
    y0 = image.height * WATERMARK_BOTTOM - cap

    layer = Image.new("L", image.size, 0)
    draw = ImageDraw.Draw(layer)
    for i in range(3):
        x = x0 + i * (slash_w + gap)
        draw.polygon([(x + slash_w * 0.45, y0), (x + slash_w, y0), (x + slash_w * 0.55, y0 + cap), (x, y0 + cap)], fill=255)
    draw.text((x0 + 3 * slash_w + 2 * gap + cap * 0.35 - left, y0 - top), text, font=font, fill=255)

    shadow = layer.filter(ImageFilter.GaussianBlur(max(1, cap * 0.08))).point(lambda v: round(v * 0.45))
    out = image.copy()
    out.paste(Image.new("RGB", image.size, (0, 0, 0)), mask=shadow)
    out.paste(Image.new("RGB", image.size, (255, 255, 255)), mask=layer.point(lambda v: round(v * 0.72)))
    return out


def encode(image, max_width, quality):
    from PIL import Image

    marked = image.width >= WATERMARK_MIN_WIDTH
    copy = image
    if copy.width > max_width:
        copy = copy.resize((max_width, round(copy.height * max_width / copy.width)), Image.LANCZOS)
    buffer = io.BytesIO()
    (watermark(copy) if marked else copy).save(buffer, "JPEG", quality=quality, optimize=True, progressive=True)
    return buffer.getvalue()


def make(photo, kind):
    """Writes the web copy and, except for grid thumbnails, the busy-mode copies."""
    image = open_source(source_of(photo))
    web = encode(image, SIZES["web"][kind], SIZES["web"]["quality"])
    (ROOT / photo).parent.mkdir(parents=True, exist_ok=True)
    (ROOT / photo).write_bytes(web)
    entry = {"source": fingerprint(source_of(photo))}
    sizes = [f"web {len(web) // 1024} KB"]
    if kind == "thumb":
        return entry, sizes
    for level in ("lite", "saver"):
        data = encode(image, SIZES[level][kind], SIZES[level]["quality"])
        target = ROOT / variant_path(photo, level)
        if len(data) > len(web) * WORTHWHILE:
            target.unlink(missing_ok=True)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        entry[level] = variant_path(photo, level)
        sizes.append(f"{level} {len(data) // 1024} KB")
    return entry, sizes


# ---- Keeping track -----------------------------------------------------------

def up_to_date(photo, entry):
    return (
        entry is not None
        and source_of(photo).is_file()
        and entry.get("source") == fingerprint(source_of(photo))
        and (ROOT / photo).is_file()
        and all((ROOT / path).is_file() for key, path in entry.items() if key != "source")
    )


def remove_orphans(manifest):
    wanted = {path for entry in manifest.values() for key, path in entry.items() if key != "source"}
    removed = []
    for level in ("lite", "saver"):
        folder = ROOT / "img" / level
        for file in sorted(folder.rglob("*")) if folder.is_dir() else []:
            if file.is_file() and file.relative_to(ROOT).as_posix() not in wanted:
                file.unlink()
                removed.append(file.relative_to(ROOT).as_posix())
    return removed


def check(photos, manifest):
    problems = [f"{photo}: no original at {source_of(photo).relative_to(ROOT)}" for photo in photos if not source_of(photo).is_file()]
    problems += [f"{photo}: web copies are missing or out of date" for photo in photos if source_of(photo).is_file() and not up_to_date(photo, manifest.get(photo))]
    problems += [f"{photo}: listed but no longer on a page" for photo in manifest if photo not in photos]
    if problems:
        print("Photos are out of date:")
        for problem in problems:
            print("  " + problem)
        print("Fix with: python3 tools/make_photo_variants.py")
        return 1
    print(f"Photos are up to date ({len(photos)} photos).")
    return 0


def main():
    parser = argparse.ArgumentParser(description="Make the website's watermarked photos from the originals in photos/.")
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 if out of date")
    parser.add_argument("--force", action="store_true", help="remake everything")
    args = parser.parse_args()

    photos = page_photos()
    old = read_manifest()
    if args.check:
        return check(photos, old)

    missing = [photo for photo in photos if not source_of(photo).is_file()]
    for photo in missing:
        print(f"{photo}: skipped, no original at {source_of(photo).relative_to(ROOT)}")

    manifest = {}
    for photo, kind in photos.items():
        if photo in missing:
            continue
        if not args.force and up_to_date(photo, old.get(photo)):
            manifest[photo] = old[photo]
            continue
        manifest[photo], sizes = make(photo, kind)
        print(f"{photo}: " + ", ".join(sizes))

    write_manifest(manifest)
    for path in remove_orphans(manifest):
        print(f"removed {path}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
