#!/usr/bin/env python3
"""Make the smaller "busy mode" copies of the site's photos.

Busy mode (netlify/guard/) swaps the photos on the page for smaller copies
while the site is busy. This script creates those copies (img/lite/ and
img/saver/) and the list the guard reads (netlify/guard/photo-variants.js).

Run it from anywhere after adding or replacing a photo:

    python3 tools/make_photo_variants.py           # create what is missing or out of date
    python3 tools/make_photo_variants.py --force   # recreate every copy (after changing SIZES)
    python3 tools/make_photo_variants.py --check   # change nothing; exit 1 if out of date

A photo without copies is not a problem for visitors: busy mode simply keeps
showing its full-size version. Creating copies needs Pillow (pip install pillow).
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = [ROOT / "index.html", ROOT / "portfolio.html"]
MANIFEST = ROOT / "netlify" / "guard" / "photo-variants.js"

# Longest allowed width in pixels, by how the page uses the photo, and JPEG quality.
SIZES = {
    "lite": {"img": 480, "background": 640, "quality": 58},
    "saver": {"img": 320, "background": 480, "quality": 40},
}
# A copy is only kept if it is at most this fraction of the original's size.
WORTHWHILE = 0.9

MANIFEST_HEADER = """\
// Generated by tools/make_photo_variants.py. Do not edit by hand.
// Photos that have smaller copies for busy mode, and where those copies are.
// "source" identifies the original the copies were made from.
export default """

IMG_TAG = re.compile(r"""\s(?:src|data-full)=["'](img/[^"'?#]+)["']""")
CSS_URL = re.compile(r"""url\(\s*["']?(img/[^"')?#]+)["']?\s*\)""")


def page_photos():
    """Photos the pages show, mapped to how they are used ("img" or "background")."""
    html = "\n".join(page.read_text(encoding="utf-8") for page in PAGES if page.is_file())
    found = {}
    for kind, pattern in (("img", IMG_TAG), ("background", CSS_URL)):
        for path in pattern.findall(html):
            if not path.lower().endswith((".jpg", ".jpeg")) or ".." in path.split("/"):
                continue
            if any(path.startswith(f"img/{level}/") for level in SIZES) or "/thumb/" in path:
                continue  # already a small copy
            if (ROOT / path).is_file():
                # A photo used both ways keeps the larger (background) size.
                if found.get(path) != "background":
                    found[path] = kind
    return dict(sorted(found.items()))


def fingerprint(path):
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()[:16]


def variant_path(photo, level):
    return f"img/{level}/{photo[len('img/'):]}"


def read_manifest():
    if not MANIFEST.is_file():
        return {}
    text = MANIFEST.read_text(encoding="utf-8")
    try:
        return json.loads(text[text.index("export default") + len("export default"):].rstrip().rstrip(";"))
    except ValueError:
        return {}


def write_manifest(manifest):
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(MANIFEST_HEADER + json.dumps(manifest, indent=2) + ";\n", encoding="utf-8")


def up_to_date(photo, entry):
    return (
        entry is not None
        and entry.get("source") == fingerprint(photo)
        and all((ROOT / path).is_file() for key, path in entry.items() if key != "source")
    )


def make_copy(photo, kind, level):
    """Write one smaller copy. Returns its path, or None if it would not save enough."""
    from PIL import Image, ImageCms, ImageOps  # imported here so --check works without Pillow
    import io

    settings = SIZES[level]
    source = ROOT / photo
    with Image.open(source) as opened:
        image = ImageOps.exif_transpose(opened)
        profile = image.info.get("icc_profile")
        keep_profile = None
        if profile:
            # Convert wide-gamut photos to sRGB so colours stay right without embedding a profile.
            try:
                image = ImageCms.profileToProfile(
                    image.convert("RGB"),
                    ImageCms.ImageCmsProfile(io.BytesIO(profile)),
                    ImageCms.createProfile("sRGB"),
                    outputMode="RGB",
                )
            except Exception:
                keep_profile = profile
        image = image.convert("RGB")
        if image.width > settings[kind]:
            height = round(image.height * settings[kind] / image.width)
            image = image.resize((settings[kind], height), Image.LANCZOS)
        buffer = io.BytesIO()
        options = {"quality": settings["quality"], "optimize": True, "progressive": True}
        if keep_profile:
            options["icc_profile"] = keep_profile
        image.save(buffer, "JPEG", **options)

    target = ROOT / variant_path(photo, level)
    if buffer.tell() > source.stat().st_size * WORTHWHILE:
        target.unlink(missing_ok=True)
        return None
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(buffer.getvalue())
    return variant_path(photo, level)


def remove_orphans(manifest):
    wanted = {path for entry in manifest.values() for key, path in entry.items() if key != "source"}
    removed = []
    for level in SIZES:
        folder = ROOT / "img" / level
        if not folder.is_dir():
            continue
        for file in sorted(folder.rglob("*")):
            if file.is_file() and file.relative_to(ROOT).as_posix() not in wanted:
                file.unlink()
                removed.append(file.relative_to(ROOT).as_posix())
    return removed


def check(photos, manifest):
    problems = [f"{photo}: copies are missing or out of date" for photo in photos if not up_to_date(photo, manifest.get(photo))]
    problems += [f"{photo}: listed but no longer on the page" for photo in manifest if photo not in photos]
    if problems:
        print("Busy-mode photo copies are out of date:")
        for problem in problems:
            print("  " + problem)
        print("Fix with: python3 tools/make_photo_variants.py")
        return 1
    print(f"Busy-mode photo copies are up to date ({len(photos)} photos).")
    return 0


def main():
    parser = argparse.ArgumentParser(description="Make the smaller busy-mode copies of the site's photos.")
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 if copies are out of date")
    parser.add_argument("--force", action="store_true", help="recreate every copy")
    args = parser.parse_args()

    photos = page_photos()
    old = read_manifest()
    if args.check:
        return check(photos, old)

    manifest = {}
    for photo, kind in photos.items():
        if not args.force and up_to_date(photo, old.get(photo)):
            manifest[photo] = old[photo]
            continue
        entry = {"source": fingerprint(photo)}
        sizes = [f"full {(ROOT / photo).stat().st_size // 1024} KB"]
        for level in SIZES:
            made = make_copy(photo, kind, level)
            if made:
                entry[level] = made
                sizes.append(f"{level} {(ROOT / made).stat().st_size // 1024} KB")
        if len(entry) > 1:
            manifest[photo] = entry
        print(f"{photo}: " + ", ".join(sizes))

    write_manifest(manifest)
    for path in remove_orphans(manifest):
        print(f"removed {path}")

    total = {"full": sum((ROOT / photo).stat().st_size for photo in manifest)}
    for level in SIZES:
        total[level] = sum((ROOT / entry.get(level, photo)).stat().st_size for photo, entry in manifest.items())
    print("Page photos in total: " + ", ".join(f"{name} {size / 1024:.0f} KB" for name, size in total.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
